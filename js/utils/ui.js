  /**
   * Get SVG Icon HTML string
   */
  getIcon(name, size = 18, className = '') {
    const raw = this.icons[name] || this.icons.info;
    if (size !== 18) {
      return raw.replace('width="18" height="18"', `width="${size}" height="${size}"`).replace('<svg ', `<svg class="${className}" `);
    }
    return className ? raw.replace('<svg ', `<svg class="${className}" `) : raw;
  },

  /**
   * Display a non-intrusive toast notification
   */
  showToast(message, type = 'info', duration = 3500) {
    let container = document.getElementById('toast-container');
    if (!container) {
      container = document.createElement('div');
      container.id = 'toast-container';
      container.className = 'toast-container';
      document.body.appendChild(container);
    }

    const toast = document.createElement('div');
    toast.className = `toast toast-${type}`;
    
    let iconKey = 'info';
    if (type === 'success') iconKey = 'check';
    if (type === 'error') iconKey = 'alertCircle';
    if (type === 'warning') iconKey = 'alertCircle';

    toast.innerHTML = `
      <span class="toast-icon">${this.getIcon(iconKey, 20)}</span>
      <span class="toast-message">${message}</span>
      <button class="modal-close-btn" style="padding:0; margin-left: auto;" onclick="this.parentElement.remove()">${this.getIcon('x', 14)}</button>
    `;

    container.appendChild(toast);

    setTimeout(() => {
      toast.style.opacity = '0';
      toast.style.transform = 'translateY(10px)';
      setTimeout(() => toast.remove(), 250);
    }, duration);
  },

  /**
   * Confirmation Dialog Modal
   */
  confirm(options = {}) {
    return new Promise((resolve) => {
      const title = options.title || 'Confirm Action';
      const message = options.message || 'Are you sure you want to proceed?';
      const confirmText = options.confirmText || 'Confirm';
      const cancelText = options.cancelText || 'Cancel';
      const isDanger = options.danger || false;

      const backdrop = document.createElement('div');
      backdrop.className = 'modal-backdrop show';
      backdrop.innerHTML = `
        <div class="modal-dialog">
          <div class="modal-header">
            <h3 class="modal-title">${title}</h3>
            <button class="modal-close-btn" id="confirm-modal-close">${BookNestUI.getIcon('x', 20)}</button>
          </div>
          <div class="modal-body">
            <p>${message}</p>
          </div>
          <div class="modal-footer">
            <button class="btn btn-ghost" id="confirm-modal-cancel">${cancelText}</button>
            <button class="btn ${isDanger ? 'btn-danger' : 'btn-primary'}" id="confirm-modal-ok">${confirmText}</button>
          </div>
        </div>
      `;

      document.body.appendChild(backdrop);

      const cleanup = (res) => {
        backdrop.classList.remove('show');
        setTimeout(() => backdrop.remove(), 200);
        resolve(res);
      };

      backdrop.querySelector('#confirm-modal-ok').onclick = () => cleanup(true);
      backdrop.querySelector('#confirm-modal-cancel').onclick = () => cleanup(false);
      backdrop.querySelector('#confirm-modal-close').onclick = () => cleanup(false);
    });
  },

  /**
   * Currency & Date Formatters
   */
  formatCurrency(amount) {
    if (typeof amount !== 'number') amount = parseFloat(amount) || 0;
    return new Intl.NumberFormat('en-IN', {
      style: 'currency',
      currency: 'INR',
      maximumFractionDigits: 0
    }).format(amount);
  },

  formatDate(timestamp) {
    if (!timestamp) return 'N/A';
    const date = timestamp.toDate ? timestamp.toDate() : new Date(timestamp);
    if (isNaN(date.getTime())) return 'N/A';
    return date.toLocaleDateString('en-US', {
      year: 'numeric',
      month: 'short',
      day: 'numeric'
    });
  },

  formatDateTime(timestamp) {
    if (!timestamp) return 'N/A';
    const date = timestamp.toDate ? timestamp.toDate() : new Date(timestamp);
    if (isNaN(date.getTime())) return 'N/A';
    return date.toLocaleString('en-US', {
      year: 'numeric',
      month: 'short',
      day: 'numeric',
      hour: '2-digit',
      minute: '2-digit'
    });
  },

